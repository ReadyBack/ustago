#!/usr/bin/env node
/**
 * Regenerates src/seed/data/turkey-districts.ts from two independent
 * sources and refuses to write anything unless they agree exactly.
 * See docs/reference-data/turkey-locations.md for provenance.
 *
 *   node scripts/import-turkey-districts.mjs <districtsByCityCode.json> <il-ilce.json>
 *
 * 1. districtsByCityCode.json — npm package `turkey-neighbourhoods`
 *    (built from PTT's official postal code list, pk_list.zip).
 * 2. il-ilce.json — github.com/snrylmz/il-ilce-json (NVI district codes).
 *
 * The script never invents or "fixes" names: any disagreement aborts.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const [primaryPath, secondaryPath] = process.argv.slice(2);
if (!primaryPath || !secondaryPath) {
  console.error('usage: import-turkey-districts.mjs <districtsByCityCode.json> <il-ilce.json>');
  process.exit(2);
}

const EXPECTED_PROVINCES = 81;
const EXPECTED_DISTRICTS = 973;
const upper = (s) => s.trim().toLocaleUpperCase('tr-TR');
const collator = new Intl.Collator('tr-TR');

const primary = JSON.parse(readFileSync(primaryPath, 'utf8'));
const secondary = JSON.parse(readFileSync(secondaryPath, 'utf8'));

const byProvince = new Map();
for (const [code, names] of Object.entries(primary)) {
  const id = Number(code);
  if (!Number.isInteger(id) || id < 1 || id > 81) throw new Error(`bad plate code ${code}`);
  const cleaned = names.map((n) => n.trim());
  if (new Set(cleaned).size !== cleaned.length) throw new Error(`duplicate names in ${code}`);
  byProvince.set(id, cleaned.sort(collator.compare));
}

const errors = [];
const secondaryByProvince = new Map();
for (const province of secondary.data) {
  const id = Number(province.plaka_kodu.trim());
  secondaryByProvince.set(id, new Set(province.ilceler.map((d) => upper(d.ilce_adi))));
}
for (let id = 1; id <= 81; id += 1) {
  const a = new Set((byProvince.get(id) ?? []).map(upper));
  const b = secondaryByProvince.get(id) ?? new Set();
  for (const n of a) if (!b.has(n)) errors.push(`${id}: only in primary: ${n}`);
  for (const n of b) if (!a.has(n)) errors.push(`${id}: only in secondary: ${n}`);
}

const total = [...byProvince.values()].reduce((sum, names) => sum + names.length, 0);
if (byProvince.size !== EXPECTED_PROVINCES) errors.push(`provinces: ${byProvince.size}`);
if (total !== EXPECTED_DISTRICTS) errors.push(`districts: ${total}`);
if (errors.length > 0) {
  console.error(`Sources disagree; nothing written.\n${errors.join('\n')}`);
  process.exit(1);
}

const lines = [...byProvince.entries()]
  .sort(([a], [b]) => a - b)
  .map(([id, names]) => `  ${id}: [${names.map((n) => `'${n}'`).join(', ')}],`);

const out = `/**
 * GENERATED by scripts/import-turkey-districts.mjs — do not edit by hand.
 *
 * All ${total} districts (ilçe) of Türkiye's ${byProvince.size} provinces, keyed by plate
 * code. Names keep their Turkish spelling; slugs are derived at seed time.
 *
 * Source: PTT postal code list (postakodu.ptt.gov.tr, pk_list.zip) via the
 * npm package turkey-neighbourhoods@4.0.3 (published 2024-03-31), cross-
 * checked name by name against github.com/snrylmz/il-ilce-json. Both sources
 * agreed exactly. Provenance and update steps:
 * docs/reference-data/turkey-locations.md
 */
export const TURKEY_DISTRICT_COUNT = ${total};

export const TURKEY_DISTRICTS: Readonly<Record<number, readonly string[]>> = {
${lines.join('\n')}
};
`;

const target = resolve(
  dirname(fileURLToPath(import.meta.url)),
  '../src/seed/data/turkey-districts.ts',
);
writeFileSync(target, out);
process.stdout.write(`Wrote ${byProvince.size} provinces, ${total} districts → ${target}\n`);
